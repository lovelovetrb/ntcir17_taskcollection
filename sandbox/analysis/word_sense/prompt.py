"""Gemini に渡すプロンプト (issue #46 の判定手順)。"""

from __future__ import annotations

from analysis.word_sense.records import CATEGORIES

INSTRUCTIONS = """\
あなたは情報検索の評価者です。検索クエリと、検索で返された 1 件のテキスト (学術論文の題名と抄録) を
渡します。クエリに含まれる語の語義と、検索テキストの中でのその語の語義が一致するかを判定してください。

次の手順で考えてください。

1. クエリのどの語 (概念) が、どんな意味であれ検索テキストに現れているかを挙げる。
   字面が同じ語だけでなく、同じ概念を指す別の表現も含める。
2. 次の 4 つのうち 1 つに分類する。
   - 一致: クエリの語がクエリと同じ語義で現れ、テキストの主題がクエリの意図と合う
   - 一部一致: クエリの一部の語だけが同じ語義で現れ、残りの語は現れないか語義が違う
   - 別の意味で解釈: クエリの語は現れるが、クエリとは違う語義で使われている
   - 無関係: クエリの語 (概念) が、どの意味でも現れない
3. 「別の意味で解釈」のときだけ、クエリでの意味と検索テキストでの意味を短く書く。
   それ以外のときは reason を空にする。

境界の例:
- クエリ「故障診断」(機械や回路の故障箇所を診断する) に対し、椎間板ヘルニアの診断を述べた症例報告は
  「別の意味で解釈」(クエリ = 機械などの故障診断、検索テキスト = 病気の診断)。
- クエリ「メディア同期」(マルチメディア通信で複数のメディアの時間関係を保つ) に対し、
  抄録の無い「エコマテリアル」という題名だけのテキストは「無関係」。
- クエリ「語彙機能文法」(LFG という特定の文法理論) に対し、範疇文法を扱ったテキストは
  「一部一致」(「文法」だけが同じ語義で現れる)。

出力は JSON で、category は {categories} のいずれか、reason は文字列。
"""


def instructions() -> str:
    return INSTRUCTIONS.format(categories=" / ".join(CATEGORIES))


def build_prompt(title: str, description: str, document_text: str) -> str:
    return f"クエリの題名: {title}\nクエリの説明: {description}\n\n検索テキスト:\n{document_text}\n"
